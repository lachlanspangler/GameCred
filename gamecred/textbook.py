"""Generate docs/TEXTBOOK.md: the mechanic textbook, regenerated from live data on every export."""
from __future__ import annotations

from . import DOCS_DIR
from .taxonomy import load_taxonomy


def write(games: list[dict], analysis: dict) -> None:
    tax = load_taxonomy()
    uni = {r["mechanic"]: r for r in analysis["scopes"]["high_conf"].get("mechanics", [])}
    irr = {r["mechanic"]: r for r in ((analysis.get("irr") or {}).get("mechanics") or [])}
    trend = (analysis.get("trends") or {}).get("mechanics", {})
    curated = [g for g in games if g["source"] == "curated"]
    out = ["# The GameCred Textbook of Roguelike Mechanics", "",
           f"_{len(tax.mechanics)} mechanics · {len(tax.families)} families · evidence from {len(games)} games "
           f"({len(curated)} expert-curated). Regenerated by `make export`; do not edit by hand._", "",
           "Effects are Success Index points (0–100 scale) for games with vs without the mechanic, compared within the same tag "
           "source and documentation depth (high-confidence tags). Associations, not causes: see METHODOLOGY.md.", "",
           "## Contents", ""]
    for fid, f in tax.families.items():
        out.append(f"- [{f['name']}](#{f['name'].lower().replace(' ', '-').replace('&', '').replace('--', '-')})")
    for fid, f in tax.families.items():
        out += ["", f"## {f['name']}", "", f"_{f['desc']}_"]
        for sid, sf in f["subfamilies"].items():
            out += ["", f"### {sf['name']}", ""]
            for mid in sf["mechanics"]:
                m = tax.mechanics[mid]
                ex = sorted([g for g in curated if mid in g["mechanics"]], key=lambda g: -(g["mechanics"][mid]["intensity"] * 1e7 + (g["reviews"] or 0)))
                core = [g["name"] for g in ex if g["mechanics"][mid]["intensity"] == 3][:5]
                ev = next((f"*{g['name']}*: {g['evidence'][mid]}" for g in ex if g["evidence"].get(mid)), None)
                r = uni.get(mid, {})
                facts = []
                if r.get("status") == "ok":
                    facts.append(f"Δ {r['diff']:+.1f} (95% CI {r['ci_lo']:+.1f}…{r['ci_hi']:+.1f}) · **{r['verdict']}**")
                elif r:
                    facts.append("effect: insufficient data")
                if r:
                    facts.append(f"in {r['prevalence']:.0%} of games")
                if irr.get(mid, {}).get("kappa") is not None:
                    facts.append(f"tagging κ {irr[mid]['kappa']:.2f}")
                sl = trend.get(mid, {}).get("slope")
                if sl is not None and abs(sl) >= 0.005:
                    facts.append(f"{'rising' if sl > 0 else 'declining'} {sl * 100:+.1f} pp/yr")
                out.append(f"**{m.name}** (`{mid}`) — {m.desc}")
                if facts:
                    out.append(f"  ")
                    out.append(f"  {' · '.join(facts)}")
                if core or ex:
                    out.append(f"  ")
                    also = [g["name"] for g in ex if g["name"] not in core][:4]
                    out.append(f"  Core in: {', '.join(core) if core else '—'}" + (f" · also: {', '.join(also)}" if also else ""))
                if ev:
                    out.append(f"  ")
                    out.append(f"  > {ev}")
                out.append("")
    (DOCS_DIR / "TEXTBOOK.md").write_text("\n".join(out) + "\n")
